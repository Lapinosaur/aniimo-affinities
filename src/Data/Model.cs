using System;
using System.Drawing;
using System.Globalization;
using System.IO;
using System.Reflection;
using System.Collections.Generic;

namespace AniimoAffinities
{
    internal static class Model
    {
        internal static readonly string[] Names;
        internal static readonly Color[] Colors;
        private static readonly Dictionary<long, double[]> Rows = new Dictionary<long, double[]>();
        private static readonly Dictionary<double, string> FactorLabels = new Dictionary<double, string>();
        private static readonly Dictionary<int, string> MatrixHighlights = new Dictionary<int, string>();
        // Inputs: build-generated shared matchup projections. Output: immutable product data. Fallback: none. Raises: missing/corrupt embedded data. Effects: reads own assembly.
        static Model()
        {
            var names = new List<string>();
            var colors = new List<Color>();
            using (var reader = Reader("types.txt"))
            {
                string line;
                while ((line = reader.ReadLine()) != null)
                {
                    var parts = line.Split('|');
                    names.Add(parts[0]);
                    colors.Add(ColorTranslator.FromHtml(parts[1]));
                }
            }
            Names = names.ToArray();
            Colors = colors.ToArray();
            using (var reader = Reader("matrix-emphasis.txt"))
            {
                string line;
                while ((line = reader.ReadLine()) != null)
                {
                    var parts = line.Split('|');
                    MatrixHighlights.Add(int.Parse(parts[0]), parts[1]);
                }
            }
            using (var reader = Reader("matchups.txt"))
            {
                string line;
                while ((line = reader.ReadLine()) != null)
                {
                    var parts = line.Split('|');
                    var values = Array.ConvertAll(parts[1].Split(','), value => double.Parse(value, CultureInfo.InvariantCulture));
                    foreach (double value in values)
                        if (!FactorLabels.ContainsKey(value))
                            FactorLabels.Add(value, FormatFactor(value));
                    var indices = parts[0].Split(':');
                    Rows.Add(RowKey(int.Parse(indices[0], CultureInfo.InvariantCulture), int.Parse(indices[1], CultureInfo.InvariantCulture)), values);
                }
            }
        }
        private static StreamReader Reader(string name)
        {
            return new StreamReader(Assembly.GetExecutingAssembly().GetManifestResourceStream(name));
        }
        // Inputs: selected indices. Output: nine outgoing then nine incoming factors generated by the existing TS implementation. Fallback: duplicate secondary becomes single type. Raises: invalid index. Effects: none.
        internal static double[] Factors(int main, int secondary)
        {
            return Rows[RowKey(main, secondary == main ? -1 : secondary)];
        }
        private static long RowKey(int main, int secondary)
        {
            return ((long)main << 32) | (uint)secondary;
        }
        internal static string Factor(double value)
        {
            string label;
            return FactorLabels.TryGetValue(value, out label) ? label : FormatFactor(value);
        }
        private static string FormatFactor(double value)
        {
            return "×" + value.ToString("0.###", CultureInfo.InvariantCulture);
        }
        internal static bool MatrixBest(int fixedType, int attack, int defense)
        {
            return MatrixHighlights[fixedType][attack * 9 + defense] == '1';
        }
    }
}
